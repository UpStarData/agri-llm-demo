def xlsx_out():
    from openpyxl import Workbook
    from openpyxl.styles import Font, Alignment, PatternFill
    from openpyxl.utils import get_column_letter
    wb = Workbook()
    head = Font(bold=True, color='FFFFFF')
    fill = PatternFill('solid', fgColor='1D4ED8')
    wrap = Alignment(vertical='top', wrap_text=True)

    ws = wb.active
    ws.title = '0.说明与口径'
    ws.append(['项目', '内容'])
    for c in ws[1]:
        c.font, c.fill = head, fill
    total, count = totals()
    ws.append(['颗粒度', '一个模块 = 一行；模块内部拆解写在“子功能点”，供评估与派工'])
    ws.append(['模块数 / 工作量', '%d 个模块 / %g 人日（演示级）' % (count, total)])
    ws.append(['资源口径', '前端 1 · 后端 1 · 架构 1 · 爬虫 1 · 郭博（推理引擎）1 · 产品 1 · 项目经理 1'])
    ws.append(['工程容量', '≈175 人日（5 名工程 × 35 有效人日，扣国庆 W2）'])
    ws.append(['缺口', '≈%g 人日，需真人项目经理决策（加人 / 砍范围 / 压缩演示动线）' % (total - 175)])
    for n in NOTES:
        ws.append(['提示', n])

    ws2 = wb.create_sheet('1.功能列表')
    cols = ['编号', '所属层', '模块', '子功能点', '主责', '协作', '人日', '现状', '里程碑', '优先级']
    ws2.append(cols)
    for c in ws2[1]:
        c.font, c.fill = head, fill
    for row in MODULES:
        _id, layer, name, points, owner, collab, days, status, ms, pri = row
        ws2.append([_id, layer, name, ' / '.join(points), owner, collab, days, status, ms, pri])
    widths = [8, 12, 30, 68, 8, 14, 6, 8, 8, 8]
    for i, w in enumerate(widths, 1):
        ws2.column_dimensions[get_column_letter(i)].width = w
    for r in ws2.iter_rows(min_row=2):
        for c in r:
            c.alignment = wrap
    ws2.freeze_panes = 'A2'

    ws3 = wb.create_sheet('2.按负责人汇总')
    ws3.append(['负责人', '模块数', '人日', '可用人日', '差额', '主要模块'])
    for c in ws3[1]:
        c.font, c.fill = head, fill
    for k, (n, d) in owner_totals().items():
        mods = '、'.join('%s %s' % (r[0], r[2]) for r in MODULES if r[4] == k)
        ws3.append([k, n, d, 35, round(d - 35, 1), mods])
    for i, w in enumerate([10, 8, 8, 10, 8, 90], 1):
        ws3.column_dimensions[get_column_letter(i)].width = w
    for r in ws3.iter_rows(min_row=2):
        for c in r:
            c.alignment = wrap

    ws4 = wb.create_sheet('3.按层汇总')
    ws4.append(['层', '模块数', '人日'])
    for c in ws4[1]:
        c.font, c.fill = head, fill
    for k, (n, d) in layer_totals().items():
        ws4.append([k, n, d])
    ws4.append(['合计', count, total])
    for i, w in enumerate([14, 8, 8], 1):
        ws4.column_dimensions[get_column_letter(i)].width = w

    ws5 = wb.create_sheet('4.里程碑（粗）')
    ws5.append(['里程碑', '时间窗', '内容', '版本'])
    for c in ws5[1]:
        c.font, c.fill = head, fill
    for m, t, c_, v in MILESTONES:
        ws5.append([m, t, c_, v])
    for i, w in enumerate([10, 16, 60, 14], 1):
        ws5.column_dimensions[get_column_letter(i)].width = w
    for r in ws5.iter_rows(min_row=2):
        for c in r:
            c.alignment = wrap

    ws6 = wb.create_sheet('5.可延后（砍范围参考）')
    ws6.append(['编号', '模块', '人日', '优先级'])
    for c in ws6[1]:
        c.font, c.fill = head, fill
    s = 0
    for row in MODULES:
        if row[9] in ('P1', 'P2'):
            ws6.append([row[0], row[2], row[6], row[9]])
            s += row[6]
    ws6.append(['合计可延后', '', s, ''])
    for i, w in enumerate([10, 34, 8, 10], 1):
        ws6.column_dimensions[get_column_letter(i)].width = w
    wb.save(XLSX)

